package org.github.krkr2

import android.content.Context
import org.github.krkr2.data.TimeFormat

/**
 * Static text bundles for the launcher. Two locales (EN/ZH) are bundled
 * inline so we don't need to ship strings.xml for every Compose-only string.
 *
 * Field set is aligned with KrKr2-Next's `AppLocalizations` so the UI layer
 * can use the same vocabulary.
 */
object LauncherStrings {
    data class Texts(
        // Brand / chrome
        val title: String,
        val settings: String,
        val grantStorage: String,
        // Library
