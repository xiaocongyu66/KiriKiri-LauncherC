        // Time formatter
        override val justNow: String,
        val minutesAgoFmt: (Int) -> String,
        val hoursAgoFmt: (Int) -> String,
        val daysAgoFmt: (Int) -> String,
        // Misc
        val aboutVersion: String,
        val aboutDescription: String,
    ) : TimeFormat.Strings {
        override fun minutesAgo(n: Int): String = minutesAgoFmt(n)
        override fun hoursAgo(n: Int): String = hoursAgoFmt(n)
        override fun daysAgo(n: Int): String = daysAgoFmt(n)
    }

